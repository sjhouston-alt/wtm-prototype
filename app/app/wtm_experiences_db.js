const getPetFriendly     = ()    => EXPERIENCES.filter(e => e.pet_friendly);
const getKidFriendly     = ()    => EXPERIENCES.filter(e => e.kid_friendly);
const getNeedsWaiver     = ()    => EXPERIENCES.filter(e => e.waiver_required);
const getNeedsVerification = ()  => EXPERIENCES.filter(e => e.verification_level !== 'none');

// Tier preview: experiences that show as teaser to the tier below
const getPreviewsForTier = (tier) =>
  EXPERIENCES.filter(e => e.preview_for_tier === tier).slice(0, 3);

// Pricing
function calculateTotal(exp, guests, addons = []) {
  const guestFee    = Math.max(0, guests - 2) * exp.price_per_guest;
  const addonTotal  = addons.reduce((s, a) => s + a.price, 0);
  return exp.price_base + guestFee + addonTotal;
}
const isInstallmentEligible = (total) => total >= INSTALLMENT_MIN_TOTAL;

// Points — NEVER expire
function calculatePoints(exp, total, memberTier) {
  const tier = TIERS[memberTier] || TIERS.rookie;
  return Math.round(total * exp.points_mult * tier.points_mult);
}

// QE
function getQEForBooking  (price) { return getQEWeight(price); }
function calculateAnnualQE(bookings) {
  let freeQE = 0, paidQE = 0;
  for (const b of bookings) {
    const w = getQEWeight(b.price);
    if (b.price === 0) freeQE += w;
    else paidQE += w;
  }
  const total      = freeQE + paidQE;
  const maxFree    = total * FREE_QE_CAP_PCT;
  const capped     = Math.min(freeQE, maxFree);
  return Math.round((paidQE + capped) * 100) / 100;
}
function getTierForQE(qe) {
  if (qe >= TIERS.local.qe_min)   return 'local';
  if (qe >= TIERS.regular.qe_min) return 'regular';
  return 'rookie';
}

// Cancellation
function getCancellationPolicy(exp) {
  return CANCELLATION_POLICIES[exp.cancellation_policy] || CANCELLATION_POLICIES.flexible;
}

// Current rotating rewards (call with current month 0-11)
function getCurrentRotatingRewards(monthIndex) {
  const seasons = [
    'winter','winter',           // Jan, Feb
    'spring','spring','spring',  // Mar, Apr, May
    'summer','summer','summer',  // Jun, Jul, Aug
    'fall','fall','fall',        // Sep, Oct, Nov
    'winter',                    // Dec
  ];
  const season = seasons[monthIndex] || 'fall';
  return REDEMPTION_CATALOG.rotating[season] || [];
}

// Active rewards for display (3 core + 3 rotating, max 6)
function getActiveRedemptions(memberTier, monthIndex = new Date().getMonth()) {
  const tier   = memberTier || 'rookie';
  const tierOrder = ['rookie','regular','local'];
  const tierIdx   = tierOrder.indexOf(tier);
  const core    = REDEMPTION_CATALOG.core.filter(r =>
    tierOrder.indexOf(r.required_tier) <= tierIdx
  );
  const rotating = getCurrentRotatingRewards(monthIndex).filter(r =>
    tierOrder.indexOf(r.required_tier) <= tierIdx
  );
  const localOnly = tier === 'local' ? REDEMPTION_CATALOG.local_only : [];
  return [...core, ...rotating, ...localOnly].slice(0, 6);
}

// Favorites (persisted in localStorage)
function getFavoriteIds() {
  try { return JSON.parse(localStorage.getItem('wtm-favorites') || '[]'); }
  catch { return []; }
}
function toggleFavorite(experienceId) {
  const favs = getFavoriteIds();
  const idx  = favs.indexOf(experienceId);
  if (idx >= 0) favs.splice(idx, 1);
  else favs.push(experienceId);
  localStorage.setItem('wtm-favorites', JSON.stringify(favs));
  return favs.includes(experienceId);
}
function isFavorited(experienceId) { return getFavoriteIds().includes(experienceId); }
function getFavoriteExperiences()  { return EXPERIENCES.filter(e => isFavorited(e.id)); }

