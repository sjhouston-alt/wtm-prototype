function getQEWeight(price) {
  if (price === 0) return QE_WEIGHTS.free;
  if (price < 250) return QE_WEIGHTS.standard;
  if (price < 500) return QE_WEIGHTS.premium;
  return QE_WEIGHTS.exclusive;
}

